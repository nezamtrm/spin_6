# app/pipeline/prompt.py
"""
مرحله ۶ از Pipeline: ساخت پرامپت.

خروجی این ماژول دقیقا همان چیزی است که
`app/llm/vllm_client.stream_chat_completion(messages=...)` انتظار دارد:
یک لیست از dict های {"role": ..., "content": ...} با فرمت چت OpenAI/vLLM.
"""
from app.pipeline.schemas import (
    MAX_HISTORY_MESSAGES,
    MAX_MESSAGE_CONTENT_LENGTH,
    DEFAULT_DISCLAIMER,
)

# نقش‌های مجاز طبق اسکیمای Message در قرارداد
_ALLOWED_ROLES: frozenset[str] = frozenset({"user", "assistant"})

# ---------------------------------------------------------------------------
# پرامپت سیستمی
# ---------------------------------------------------------------------------
# این متن مرزهای ایمنی مدل را تعیین می‌کند: پزشک عمومی، فقط اطلاعات کلی،
# بدون تشخیص قطعی، بدون دوز دقیق دارو، ارجاع به ۱۱۵ در موارد اورژانسی و
# یادآوری اینکه این گفتگو جایگزین ویزیت حضوری نیست.
SYSTEM_PROMPT: str = f"""تو یک دستیار هوشمند پزشکی فارسی‌زبان هستی که در نقش یک «پزشک عمومی» به کاربران اطلاعات اولیه می‌دهی.

قوانین الزامی که تحت هیچ شرایطی نباید نقض شوند:
۱. فقط اطلاعات پزشکی عمومی و آموزشی ارائه بده. هرگز تشخیص قطعی نده؛ به جای «شما فلان بیماری را دارید» بگو «این علائم می‌تواند نشانه چند مورد باشد».
۲. هرگز دوز دقیق دارو، تعداد قرص، فاصله مصرف یا نسخه دارویی ننویس. اگر کاربر دوز پرسید، توضیح بده که تعیین دوز فقط بر عهده پزشک معالج است.
۳. اگر علائم اورژانسی محتمل بود (مانند درد شدید قفسه سینه، تنگی نفس شدید، ضعف یا فلج ناگهانی یک سمت بدن، اختلال هوشیاری، خونریزی کنترل‌نشده، تشنج، مسمومیت یا فکر خودکشی)، قبل از هر توضیحی کاربر را به تماس فوری با اورژانس ۱۱۵ یا مراجعه به نزدیک‌ترین اورژانس راهنمایی کن.
۴. فقط به سوالات حوزه سلامت پاسخ بده. اگر سوال خارج از این حوزه بود، محترمانه توضیح بده که فقط در زمینه سلامت می‌توانی کمک کنی.
۵. اطلاعات هویتی کاربر (کد ملی، شماره تماس، آدرس) را نه بپرس و نه تکرار کن.
۶. اگر منابع بازیابی‌شده در اختیارت گذاشته شد، پاسخ را بر همان‌ها استوار کن و از خودت مطلب نساز. اگر اطلاعات کافی نبود، صادقانه بگو مطمئن نیستی.

سبک پاسخ:
- فارسی روان، محترمانه و ساده؛ از اصطلاحات تخصصی فقط در حد لازم و همراه با توضیح استفاده کن.
- کوتاه و ساختارمند بنویس: ابتدا جمع‌بندی کوتاه از وضعیت، سپس توصیه‌های عملی به صورت فهرست، و در انتها اینکه چه زمانی حتما باید به پزشک مراجعه کند.
- در پایان هر پاسخ این یادآوری را بیاور: «{DEFAULT_DISCLAIMER}»"""

# ---------------------------------------------------------------------------
# رفتار «اول سوال تکمیلی بپرس، بعد ارجاع بده» - مرحله ۴.۵ (بعد از روتر)
# ---------------------------------------------------------------------------
# نکته صادقانه درباره این بخش: این یک state-machine واقعی با ردیابی
# slot-به-slot نیست؛ یک دستورالعمل به مدل زبانی است که از conversation_history
# برای تصمیم «اول‌بار است یا نه» استفاده می‌کند. برای فاز ۱ و با مدلی به‌قدرت
# Qwen2.5-32B-Instruct پیروی از این دستورالعمل معمولا قابل‌اتکا است، ولی
# تضمین سخت‌افزاری/schema-level ندارد. اگر رفتار قطعی‌تر لازم شد، باید یک
# state واقعی (مثلا شمارنده سوالات پرسیده‌شده در session) اضافه شود.
SPECIALTY_FOLLOWUP_HINTS: dict[str, str] = {
    "gynecology": "از کی شروع شده؟ سیکل قاعدگی منظم است؟ احتمال بارداری هست؟ درد یا خونریزی همراه دارد؟",
    "orthopedics": "از کی شروع شده؟ بعد از ضربه/تصادف بوده یا خودبه‌خود؟ محل دقیق درد کجاست؟ با حرکت بدتر می‌شود؟",
    "dentistry": "کدام دندان/ناحیه درد می‌کند؟ به سرما یا گرما حساس شده؟ تب یا تورم صورت همراه دارد؟ از کی شروع شده؟",
    "speech_therapy": "سن فرد چند است؟ مشکل از تولد بوده یا اخیرا شروع شده؟ در تلفظ است، روانی گفتار (لکنت) یا درک زبان؟",
    "general_surgery": "درد از کی شروع شده و محل دقیقش کجاست؟ تب، تهوع یا استفراغ همراه دارد؟ سابقه جراحی قبلی دارید؟",
    "general_practice": "علائم از کی شروع شده؟ تب دارید؟ آیا داروی خاصی مصرف می‌کنید یا بیماری زمینه‌ای دارید؟",
}


def _specialty_directive(specialty: str | None, specialty_fa: str | None, is_first_turn: bool) -> str:
    """متن اضافه‌ای که به سیستم‌پرامپت چسبانده می‌شود تا مدل بداند تخصص
    تشخیص‌داده‌شده توسط روتر (مرحله ۴) چیست و در چه مرحله‌ای از مکالمه است."""
    if not specialty:
        return ""

    hint = SPECIALTY_FOLLOWUP_HINTS.get(specialty, "")
    label = specialty_fa or specialty

    if is_first_turn:
        return (
            f"\n\nتخصص تشخیص‌داده‌شده برای این سوال توسط روتر: «{label}».\n"
            "این اولین پیام کاربر در این گفتگو است. اگر اطلاعات فعلی برای یک توصیه "
            "مفید کافی نیست، به‌جای پاسخ کامل، حداکثر ۲ سوال کوتاه و دقیق بپرس تا "
            "تصویر روشن‌تر شود (نمونه سوالات مرتبط با همین تخصص: "
            f"{hint}). سوال‌ها را به‌صورت فهرست کوتاه بپرس، نه یک پاراگراف بلند. "
            "اگر همان اول اطلاعات کافی بود، مستقیم برو سراغ توصیه و در پایان صریح "
            f"بگو که برای بررسی دقیق‌تر باید به «{label}» مراجعه کند."
        )
    return (
        f"\n\nتخصص تشخیص‌داده‌شده: «{label}». این ادامه یک گفتگوست - در تاریخچه زیر "
        "احتمالا قبلا سوال تکمیلی پرسیده‌ای. اگر کاربر به آن سوال‌ها جواب داده، "
        "دیگر سوال تکراری نپرس؛ جمع‌بندی کوتاه از وضعیت بده، توصیه‌های عملی ارائه "
        f"کن و در پایان صریح ارجاع بده: «برای بررسی دقیق‌تر به {label} مراجعه کنید»."
    )


def _sources_block(sources: list[dict] | None) -> str:
    """متن منابع بازیابی‌شده (RAG) را به شکل خوانا برای مدل می‌سازد - دقیقا
    همان چیزی که قانون ۶ در SYSTEM_PROMPT به آن ارجاع می‌دهد
    ("اگر منابع بازیابی‌شده در اختیارت گذاشته شد..."). اگر منبعی نبود
    (RAG چیزی پیدا نکرد یا اصلا وصل نیست)، هیچ بلوکی اضافه نمی‌شود و مدل
    فقط طبق مرزهای عمومی SYSTEM_PROMPT جواب می‌دهد."""
    if not sources:
        return ""
    lines = ["\n\nمنابع بازیابی‌شده (فقط برای استناد؛ متن کامل را کپی نکن، خلاصه/بازنویسی کن):"]
    for i, s in enumerate(sources, 1):
        title = s.get("title", "")
        lines.append(f"{i}. {title}")
    return "\n".join(lines)


def build_prompt(
    history: list[dict],
    current_query: str,
    specialty: str | None = None,
    specialty_fa: str | None = None,
    sources: list[dict] | None = None,
) -> list[dict[str, str]]:
    """
    ساخت لیست پیام‌ها برای ارسال به vLLM.

    ورودی‌ها:
      history: تاریخچه گفتگو با ساختار اسکیمای Message
               (کلیدهای role و content؛ کلیدهای اضافی مثل timestamp نادیده
               گرفته می‌شوند چون vLLM آن‌ها را نمی‌پذیرد).
      current_query: سوال فعلی کاربر (بهتر است متن sanitized مرحله ۱ باشد).
      specialty: کلید انگلیسی تخصص تشخیص‌داده‌شده توسط روتر (مرحله ۴)،
                 مثلا "dentistry" - اختیاری، اگر داده نشود سیستم‌پرامپت
                 عمومی بدون بخش تخصص/ارجاع استفاده می‌شود.
      specialty_fa: نام فارسی همان تخصص، برای نمایش در متن پرامپت.
      sources: منابع بازیابی‌شده توسط app/pipeline/retriever.py (اختیاری) -
               لیست dict سازگار با اسکیمای Source. اگر خالی/None باشد یعنی
               RAG چیزی پیدا نکرده (یا اصلا وصل نیست)؛ مدل بدون منبع، فقط
               طبق مرزهای عمومی SYSTEM_PROMPT پاسخ می‌دهد.

    خروجی:
      [{"role": "system", ...}, ...تاریخچه..., {"role": "user", "content": current_query}]

    طبق قرارداد، conversation_history حداکثر ۶ پیام دارد؛ اگر بیشتر بود فقط
    ۶ پیام آخر نگه داشته می‌شود تا latency کنترل شود. ترتیب پیام‌ها حفظ می‌شود.
    """
    cleaned_history = _normalize_history(history)
    is_first_turn = len(cleaned_history) == 0

    system_content = (
        SYSTEM_PROMPT
        + _specialty_directive(specialty, specialty_fa, is_first_turn)
        + _sources_block(sources)
    )

    messages: list[dict[str, str]] = [{"role": "system", "content": system_content}]
    messages.extend(cleaned_history)
    messages.append({"role": "user", "content": current_query})
    return messages


def _normalize_history(history: list[dict]) -> list[dict[str, str]]:
    """
    تاریخچه ورودی را به فرمت چت vLLM تبدیل می‌کند:
    حذف پیام‌های خراب یا خالی، حذف نقش‌های غیرمجاز، برش محتوای بلندتر از
    ۱۰۰۰ کاراکتر (طبق Message.content) و نگه داشتن فقط ۶ پیام آخر.
    """
    if not history:
        return []

    cleaned: list[dict[str, str]] = []
    for message in history:
        if not isinstance(message, dict):
            continue
        role = message.get("role")
        content = message.get("content")
        if role not in _ALLOWED_ROLES or not isinstance(content, str):
            continue
        content = content.strip()
        if not content:
            continue
        cleaned.append(
            {"role": role, "content": content[:MAX_MESSAGE_CONTENT_LENGTH]}
        )

    # فقط ۶ پیام آخر - قدیمی‌ترها دور ریخته می‌شوند
    return cleaned[-MAX_HISTORY_MESSAGES:]
